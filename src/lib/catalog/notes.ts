export const CAT_ORDER: string[] = ["خشبية","شرقية وراتنجات","مسكية وحيوانية","زهرية","حمضيات","توابل","حلوة وجورماند","مشروبات (بوزية)","عشبية وخضراء","بحرية","فواكه","أخرى"];

/** Count how many perfumes contain each note */
export function populateNotes(data: { notes: string[] }[]): void {
  NOTES_DB.forEach((nt) => {
    nt.count = data.filter((d) => d.notes.some((x) => x.includes(nt.n))).length;
  });
}

/** Get notes sorted by usage count (only present ones) */
export function getPresentNotes(): NoteEntry[] {
  return NOTES_DB.filter((nt) => (nt.count ?? 0) > 0).sort(
    (a, b) => (b.count ?? 0) - (a.count ?? 0)
  );
}

/** Build <option> HTML for note select dropdown */
export function notesOptionsHtml(): string {
  const sorted = getPresentNotes();
  return sorted
    .map((nt) => '<option value="' + nt.n + '">' + nt.icon + ' ' + nt.n + ' (' + String(nt.count ?? 0) + ')</option>')
    .join('');
}

/** Check if a note name is valid */
export function isValid(name: string): boolean {
  return NOTES_DB.some((nt) => nt.n === name);
}

/** Get notes grouped by category, sorted by count within each group */
export function glossaryGroups(): { cat: string; items: NoteEntry[] }[] {
  const present = getPresentNotes();
  return CAT_ORDER
    .map((c) => ({ cat: c, items: present.filter((nt) => nt.cat === c) }))
    .filter((g) => g.items.length > 0);
}
